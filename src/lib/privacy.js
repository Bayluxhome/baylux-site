// Очистка объекта объявления от служебных/персональных полей перед отправкой в браузер.
//
// owner_email и tg_user_id нужны только серверу — по ним объявление связывается с карточкой
// риелтора. Если передать объект в клиентский компонент как есть, эти поля попадают в HTML
// страницы и видны любому посетителю (проверено: в каталоге светились личные email владельцев).
//
// Модуль намеренно без импортов серверного кода — его подключают и клиентские компоненты.
export function stripPrivate(u) {
  if (!u || typeof u !== "object") return u;
  const { owner_email, tg_user_id, owner_phone, owner_name, owner_tg_username, source_ref, ...rest } = u;
  return rest;
}
